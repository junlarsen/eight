#include "xd/TableGen/DiagnosticEmitter.h"
#include "llvm/TableGen/Record.h"
#include "llvm/TableGen/TableGenBackend.h"
#include <cassert>

using namespace llvm;
using namespace xd;

auto DiagnosticEmitter::emit(raw_ostream &OS) -> bool {
  emitSourceFileHeader("File generated by xd-tablegen", OS);
  auto Diagnostics = RK.getAllDerivedDefinitions("Diagnostic");
  // Process diagnostics by emitting their kinds
  assert(Diagnostics.size() > 0 &&
         "Cannot emit diagnostics with zero configured records. This is "
         "required for generating the enum kind");
  OS << "#ifndef XD_BASIC_DIAGNOSTICS_TD" << "\n";
  OS << "#define XD_BASIC_DIAGNOSTICS_TD" << "\n\n";
  OS << "#include <cstdint>" << "\n";
  OS << "#include <string_view>" << "\n";
  OS << "#include <string>" << "\n";
  OS << "\n";
  OS << "namespace xd {" << "\n";
  OS << "enum class DiagnosticKind: uint8_t {" << "\n";
  for (auto *Diag : Diagnostics)
    OS << "  " << Diag->getName() << "," << "\n";
  OS << "};\n";

  // Emit sentinel values for first and last record in order to allow RTTI to
  // use constant kinds.
  auto *FirstRK = Diagnostics[0];
  auto *EndRK = Diagnostics[Diagnostics.size() - 1];
  OS << "static auto FirstDiagnosticKind = DiagnosticKind::"
     << FirstRK->getName() << ";" << "\n";
  OS << "static auto LastDiagnosticKind = DiagnosticKind::" << EndRK->getName()
     << ";" << "\n";

  OS << "\n"
     << "#include \"xd/Basic/Diagnostic.h.inc\"" << "\n";

  for (auto *Diag : Diagnostics)
    emitDiagnosticClass(*Diag, OS);

  // Close the namespace and include guard
  OS << "} // namespace xd" << "\n\n";
  OS << "#endif // XD_BASIC_DIAGNOSTICS_TD" << "\n";
  return false;
}

auto DiagnosticEmitter::emitDiagnosticClass(const Record &R,
                                            raw_ostream &OS) -> void {
  std::string ClassName = (R.getName() + "Diagnostic").str();
  OS << "\n";
  OS << "class " << ClassName << " : public Diagnostic {" << "\n";
  OS << "  inline static std::string_view Format = \""
     << R.getValueAsString("format") << "\";" << "\n";
  // Generate each of the diagnostic parameters
  auto ArgumentRecords = R.getValueAsListOfDefs("arguments");
  for (auto *Arg : ArgumentRecords) {
    auto *TypeDef = Arg->getValueAsDef("type");
    OS << "  " << TypeDef->getValueAsString("cxxType") << " "
       << Arg->getValueAsString("name") << ";" << "\n";
  }
  OS << "public:" << "\n";
  // Generate the constructor for the class with the argument list types.
  OS << "  explicit " << ClassName << "(";
  // Generate each of the diagnostic arguments
  for (auto *Arg : ArgumentRecords) {
    auto *TypeDef = Arg->getValueAsDef("type");
    OS << TypeDef->getValueAsString("inputType") << " "
       << Arg->getValueAsString("name");
    if (Arg != ArgumentRecords.back()) {
      OS << ", ";
    }
  }
  OS << ") : Diagnostic(DiagnosticKind::" << R.getName() << ")";
  // Initialize each of the members with the arguments
  for (auto *Arg : ArgumentRecords) {
    OS << ", " << Arg->getValueAsString("name") << "("
       << Arg->getValueAsString("name") << ")";
  }
  OS << " {}" << "\n";
  // Add LLVM-style RTTI instance type check
  OS << "  static bool classof(const " << ClassName << " *Diagnostic) {"
     << "\n";
  OS << "    return Diagnostic->getKind() == DiagnosticKind::" << R.getName()
     << ";" << "\n";
  OS << "  }" << "\n";
  // End the class definition
  OS << "};" << "\n";
}
